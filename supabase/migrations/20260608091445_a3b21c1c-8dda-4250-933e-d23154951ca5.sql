## أولاً: ما المقصود بالدراسة المرورية (Traffic Impact Study)؟

الدراسة المرورية ليست مجرد مخطط كروكي أو تقرير إنشائي عابر، بل هي تحليل هندسي وعلمي متكامل قائم على محاكاة واقعية لحركة البيانات. تُستخدم هذه الدراسة لتقييم وفحص التأثير المحتمل والعبء الذي سيلقيه أي مشروع جديد (أو تعديل في نشاط قائم) على شبكة الطرق والتقاطعات المحيطة به.

الهدف الأساسي من الدراسة هو التنبؤ بالحجم المروري الذي سيولّده المشروع، وتقديم حلول هندسية وقائية تضمن عدم تسبب هذا المشروع في حدوث اختناقات مرورية، مع تحقيق انسيابية كاملة وآمنة لحركة دخول وخروج المركبات والزوار من وإلى الموقع، بما يتماشى مع خطة السلامة المرورية المستدامة للمدينة.

## ثانياً: متى تكون الدراسة المرورية متطلباً إلزامياً؟

لا تُطلب الدراسة المرورية لجميع المباني البسيطة كالفلل السكنية الصغيرة، وإنما تُفرض بشكل قطعي على المشاريع ذات الجذب المروري العالي، أو التي تقع في قطاعات حيوية. تتلخص الحالات التي يُلزم فيها المستثمر بتقديم دراسة مرورية فيما يلي:

- **كثافة الزوار والمركبات المتوقعة:** المشاريع التي يتوقع أن تجتذب مئات أو آلاف المركبات يومياً، مثل المجمعات التجارية (المولات)، والمراكز الطبية والمستشفيات، والجامعات والمدارس الأهلية الكبرى، وصالات الأفراح والمؤتمرات.
- **الموقع الجغرافي الحرج:** إذا كان المشروع يقع على شوارع تجارية رئيسية، أو محاور شريانية متفرعة، أو بالقرب من تقاطعات حرجة تعاني أصلاً من تكدس مروري في أوقات الذروة.
- **الأنشطة التي تتطلب مرافق خاصة:** المنشآت التي تستدعي توفير مواقف سيارات بأعداد كبيرة، أو مسارات مخصصة لحافلات النقل والخدمات اللوجستية.
- **التقديم على رخص البناء أو التشغيل الجديدة:** عند البدء في إجراءات إصدار الترخيص عبر منصة "بلدي" للمشاريع التجارية والخدمية.
- **تغيير وتعديل استخدام العقار:** تحويل منشأة قائمة من نشاط ذي جذب مروري منخفض إلى نشاط آخر ذي جذب مروري مرتفع.

الجهات الرسمية التي تطلب وتدقق هذه الدراسة عادةً هي: **أمانة منطقة الرياض**، **الإدارة العامة للمرور**، **الهيئة العامة للنقل**، و**المديرية العامة للدفاع المدني** لضمان خلو المداخل والمخارج من أي عوائق تعيق آليات الطوارئ.

## ثالثاً: ما هي المكونات الفنية للتقرير المروري المعتمد؟

يقوم المهندسون المختصون في "ارت ترافيك" بإعداد التقرير المروري وفقاً لأعلى المعايير الهندسية المعمول بها في المملكة العربية السعودية:

**1. رصد وتحليل الوضع الراهن (Baseline Assessment):** مسح ميداني شامل للمنطقة المحيطة بالمشروع، وحساب أحجام المرور الحالية في الشوارع المحيطة والتقاطعات القريبة خلال فترات الذروة الصباحية والمسائية، لتحديد "مستوى الخدمة" الحالي للطريق (Level of Service - LOS).

**2. توليد وتوزيع الرحلات المستقبلية (Trip Generation & Distribution):** باستخدام معادلات هندسية ونماذج عالمية معتمدة (مثل دليل معهد مهندسي النقل ITE)، يتم حساب عدد المركبات التي سيجذبها المشروع، ثم توزيع هذه الرحلات على شبكة الشوارع المتاحة لمعرفة الأثر المستقبلي.

**3. دراسة الطاقة الاستيعابية للمواقف (Parking Assessment):** مقارنة عدد المواقف التي يوفرها المشروع مع الاشتراطات النظامية لكود البناء السعودي وأمانة الرياض، وضمان كفاية المواقف لمنع تكدس السيارات في الشوارع العامة المحيطة.

**4. التصميم الهندسي للمداخل والمخارج (Geometric Design):** تحديد المواقع المثالية لبوابات الدخول والخروج، وتصميم حارات التباطؤ والتسارع، وضمان توفير مسافات الرؤية الآمنة للسائقين، والتأكد من نصف قطر الدوران المناسب لسيارات الإطفاء والإنقاذ.

**5. تقديم الحلول والتوصيات (Mitigation Measures):** إذا أظهرت المحاكاة وجود تأثير سلبي، تقدم الدراسة حلولاً عملية مثل: إعادة برمجة الإشارات المرورية المحيطة، إضافة حارة تدوير للخلف (U-Turn)، تحسين اللوحات الإرشادية، أو تعديل التصميم الداخلي للمواقف.

